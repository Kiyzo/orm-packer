    public const string Russian = "ru";
    public const string English = "en";

    public static string Language { get; private set; } = English;

    private static IReadOnlyDictionary<string, string> _strings;

    static Localization() => _strings = EnglishStrings;

    public static event Action? Changed;

    public static void Initialize(CultureInfo uiCulture) =>
        SetLanguage((uiCulture?.TwoLetterISOLanguageName ?? English)
            .Equals(Russian, StringComparison.OrdinalIgnoreCase) ? Russian : English);

    public static void SetLanguage(string language)
    {
        Language = language == Russian ? Russian : English;
        _strings = Language == Russian ? RussianStrings : EnglishStrings;
        Changed?.Invoke();
    }

    public static void Toggle() =>
        SetLanguage(Language == Russian ? English : Russian);

    public static string Get(string key) => _strings.TryGetValue(key, out var value) ? value : key;

